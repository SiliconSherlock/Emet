#!/usr/bin/env python3
"""Write research/review-list.md: a checklist for the person verifying the data.

    python3 tools/review_list.py

Every claim is listed once, most in need of attention first, with what it is
answered by. Run it again after editing data/claims.json. Not part of the site.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLAIMS = ROOT / "data" / "claims.json"
OUT = ROOT / "research" / "review-list.md"

NT = {"Matthew", "Mark", "Luke", "John", "Acts", "Romans", "1 Corinthians", "2 Corinthians",
      "Galatians", "Ephesians", "Philippians", "Colossians", "1 Thessalonians",
      "2 Thessalonians", "1 Timothy", "2 Timothy", "Titus", "Philemon", "Hebrews", "James",
      "1 Peter", "2 Peter", "1 John", "2 John", "3 John", "Jude", "Revelation"}

# Claims whose key verse Rabbi Singer's Outreach Judaism articles also address
# (from research/singer-comparison.md, verse-level matches).
SINGER = set("""C-001 C-002 C-006 C-007 C-008 C-009 C-010 C-011 C-012 C-013 C-015 C-018 C-020 C-026
C-027 C-032 C-048 C-053 C-058 C-059 C-067 C-072 C-073 C-075 C-076 C-077 C-078 C-079 C-080 C-081
C-082 C-083 C-086 C-092 C-093 C-096 C-098 C-102 C-120 C-143 C-146 C-147 C-148 C-158 C-160 C-167
C-170 C-177""".split())


def book(cite):
    return re.match(r"(.+) \d", cite)[1]


def main():
    claims = json.loads(CLAIMS.read_text("utf-8"))["claims"]
    rows = []
    for c in claims:
        roles = [p["role"] for p in c["passages"]]
        n_reply, n_context = roles.count("reply"), roles.count("context")
        if n_reply == 0 and n_context == 0:
            shape, priority = "the verse itself only", 0
        elif n_reply == 0:
            shape, priority = "its own context only", 1
        else:
            shape, priority = f"{n_reply} other passage{'s' if n_reply != 1 else ''}" + \
                (" + context" if n_context else ""), 2
        no_tanakh = all(book(x) in NT for x in c["cited"])
        flags = [f["kind"] for f in c.get("flags", [])]
        if no_tanakh and "not-in-tanakh" not in flags:
            flags.append("no-tanakh")
        verified = sum(1 for p in c["passages"] if p.get("verified"))
        support = c["id"] in SINGER
        rows.append((priority, support, c["id"], c, shape, flags, verified))
    rows.sort(key=lambda r: (r[0], r[1], r[2]))

    total = len(claims)
    done = sum(1 for r in rows if r[6] == len(r[3]["passages"]))
    lines = [
        "# Review list",
        "",
        "_Generated by `tools/review_list.py` from `data/claims.json`. Not part of the website._",
        "",
        "Work down the list. For each claim, read its page and confirm that every TaNaKh",
        "passage is the right verse and really answers the claim. Then set",
        '`"verified": true` and a `"source"` on each passage in `data/claims.json`.',
        "",
        f"**{done} of {total} claims fully verified.**",
        "",
        "Answered by:",
        "- *the verse itself only*: no context or other passage. Check most carefully.",
        "- *its own context only*: the claim's verse read with the verses around it.",
        "- *N other passages*: independent TaNaKh passages, with or without context.",
        "",
        "*Singer* marks claims whose key verse Rabbi Singer's Outreach Judaism articles",
        "also address (see `singer-comparison.md`): a starting point, not a verification.",
        "",
        "| ✓ | Claim | Answered by | Source check | Singer |",
        "|---|---|---|---|---|",
    ]
    for priority, support, cid, c, shape, flags, verified in rows:
        tick = "✓" if verified == len(c["passages"]) else (f"{verified}/{len(c['passages'])}" if verified else "")
        lines.append(f"| {tick} | **{cid}** {c['claim']} | {shape} | {', '.join(flags) or ''} | "
                     f"{'yes' if support else ''} |")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", "utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {total} claims, {done} fully verified.")


if __name__ == "__main__":
    main()
